 updateStatus:input=>ipcRenderer.invoke('social:update-status',input),
 planEdit:input=>ipcRenderer.invoke('social:plan-edit',input),
 deletePost:input=>ipcRenderer.invoke('social:delete-post',input),
 saveEdit:(input,fingerprint)=>ipcRenderer.invoke('social:save-edit',input,fingerprint),
 planDate:input=>ipcRenderer.invoke('social:plan-date',input),
 updateDate:(input,fingerprint)=>ipcRenderer.invoke('social:update-date',input,fingerprint),
 plan:input=>ipcRenderer.invoke('social:plan',input),
 create:(input,fingerprint)=>ipcRenderer.invoke('social:create',input,fingerprint),
 openResult:channel=>ipcRenderer.invoke('social:open',channel),
